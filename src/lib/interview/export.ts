import { APP } from "@/lib/config";
import type { SavedDebrief } from "./storage";

const SIGNALS: Record<string, string> = {
  strong_no: "Strong no",
  no: "No",
  lean_no: "Leaning no",
  lean_yes: "Leaning yes",
  yes: "Yes",
  strong_yes: "Strong yes",
};

export function signalLabel(signal: string): string {
  return SIGNALS[signal] ?? signal;
}

/** The debrief as a Markdown document the user can keep. */
export function debriefToMarkdown(saved: SavedDebrief): string {
  const { debrief } = saved;
  const lines: string[] = [
    `# Interview debrief: ${saved.roleTitle}${saved.company ? ` at ${saved.company}` : ""}`,
    "",
    `Date: ${new Date(debrief.gradedAt).toLocaleString()}`,
    `Mode: ${saved.mode}`,
    `Average score: ${debrief.average.toFixed(1)} out of 5`,
    `Overall signal: ${signalLabel(debrief.hireSignal)}`,
    "",
    debrief.overallSummary,
    "",
    "## Stage by stage",
    "",
  ];
  for (const grade of debrief.stages) {
    const stage = saved.stages.find((s) => s.id === grade.stageId);
    const record = saved.records.find((r) => r.stageId === grade.stageId);
    lines.push(`### ${grade.title}: ${grade.score}/5`, "");
    if (stage) lines.push(`Question: ${stage.question}`, "");
    if (grade.verdict) lines.push(grade.verdict, "");
    if (grade.strong.length) lines.push("What was strong:", ...grade.strong.map((s) => `- ${s}`), "");
    if (grade.missing.length) lines.push("What was missing:", ...grade.missing.map((s) => `- ${s}`), "");
    if (record?.turns.length) {
      lines.push("Your answers:");
      for (const turn of record.turns) lines.push(`- Q: ${turn.question}`, `  A: ${turn.answer || "(no answer)"}`);
      lines.push("");
    }
    if (record?.station) {
      lines.push("Checks:", ...record.station.checks.map((c) => `- ${c.passed ? "Passed" : "Failed"}: ${c.label}`), "");
    }
  }
  if (debrief.tighterAnswer) {
    lines.push(
      "## A tighter version of your weakest answer",
      "",
      `Question: ${debrief.tighterAnswer.question}`,
      "",
      debrief.tighterAnswer.answer,
      "",
      "Built only from what you said. Text in [brackets] marks a detail you still need to add.",
      "",
    );
  }
  lines.push(`Generated by ${APP.name}. Scores are an AI's assessment of a practice interview, not a hiring decision.`);
  return lines.join("\n");
}

export function exportFileName(saved: SavedDebrief): string {
  const slug = saved.roleTitle.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "interview";
  return `interview-pilot-debrief-${slug}-${saved.debrief.gradedAt.slice(0, 10)}.md`;
}

/** Saves the file in a browser, or opens the share sheet inside the Android app. */
export async function exportDebrief(saved: SavedDebrief): Promise<"downloaded" | "shared"> {
  const content = debriefToMarkdown(saved);
  const name = exportFileName(saved);
  const { Capacitor } = await import("@capacitor/core");
  if (Capacitor.isNativePlatform()) {
    const { Filesystem, Directory, Encoding } = await import("@capacitor/filesystem");
    const { Share } = await import("@capacitor/share");
    const file = await Filesystem.writeFile({ path: name, data: content, directory: Directory.Cache, encoding: Encoding.UTF8 });
    await Share.share({ title: name, files: [file.uri] });
    return "shared";
  }
  const url = URL.createObjectURL(new Blob([content], { type: "text/markdown;charset=utf-8" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = name;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
  return "downloaded";
}
